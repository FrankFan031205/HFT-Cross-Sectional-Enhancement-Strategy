def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stock-curve", required=True)
    ap.add_argument("--futures", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--tag", default="v6_gradual_1021")
    ap.add_argument("--target-total-gross", type=float, default=1.0)
    ap.add_argument("--start-gross-ratio", type=float, default=0.90)
    ap.add_argument("--min-consecutive", type=int, default=5)
    ap.add_argument("--futures-fee-rate", type=float, default=0.000023)
    ap.add_argument("--futures-leverage", type=float, default=10.0)
    ap.add_argument("--zero-initial-futures-cost", type=int, default=1)
    args = ap.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    stock_full = normalize_stock_curve(args.stock_curve)
    fut = normalize_futures(args.futures)

    start_idx = find_start_index(stock_full, args.target_total_gross, args.start_gross_ratio, args.min_consecutive)
    stock = rebase_stock_only(stock_full, start_idx)
    overlay = build_overlay(
        stock,
        fut,
        target_total_gross=args.target_total_gross,
        futures_fee_rate=args.futures_fee_rate,
        futures_leverage=args.futures_leverage,
        zero_initial_futures_cost=bool(args.zero_initial_futures_cost),
    )

    stock_s = summary_stock(stock)
    overlay_s = summary_overlay(overlay)

    stock_curve = out_dir / f"{args.tag}_stock_only_curve.csv"
    stock_summary = out_dir / f"{args.tag}_stock_only_summary.csv"
    stock_png = out_dir / f"{args.tag}_stock_only_nav.png"
    overlay_curve = out_dir / f"{args.tag}_stock_plus_futures_curve.csv"
    overlay_summary = out_dir / f"{args.tag}_stock_plus_futures_summary.csv"
    overlay_png = out_dir / f"{args.tag}_stock_plus_futures_nav.png"

    stock.to_csv(stock_curve, index=False)
    stock_s.to_csv(stock_summary, index=False)
    overlay.to_csv(overlay_curve, index=False)
    overlay_s.to_csv(overlay_summary, index=False)

    plot_stock(stock, stock_s, stock_png, "Stock-Only: Gradual Position Building, 10:21 Start")
    plot_overlay(overlay, overlay_s, overlay_png, "T+1-aware Pure-CS NAV with CSI1000 Futures Overlay, 10:21 Start")

    print("===== stock-only summary =====")
    print(stock_s.T.to_string(header=False))
    print("\n===== stock + futures summary =====")
    print(overlay_s.T.to_string(header=False))
    print("\n[start]")
    print(stock["datetime"].iloc[0])
    print("\n[saved]")
    print(stock_curve)
    print(stock_summary)
    print(stock_png)
    print(overlay_curve)
    print(overlay_summary)
    print(overlay_png)


if __name__ == "__main__":
    main()
